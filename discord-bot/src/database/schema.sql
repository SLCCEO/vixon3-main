CREATE TABLE IF NOT EXISTS public.duty_status (
  user_id TEXT PRIMARY KEY,
  status TEXT NOT NULL CHECK (status IN ('On Duty', 'Off Duty', 'LOA Pending', 'On LOA')),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.loa_requests (
  user_id TEXT PRIMARY KEY,
  user_tag TEXT NOT NULL,
  reason TEXT NOT NULL,
  status TEXT NOT NULL CHECK (status IN ('Pending', 'Approved', 'Rejected')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.warnings (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id TEXT NOT NULL,
  reason TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS warnings_user_id_created_at_idx
  ON public.warnings (user_id, created_at DESC);

ALTER TABLE public.duty_status ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.loa_requests ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.warnings ENABLE ROW LEVEL SECURITY;

CREATE OR REPLACE FUNCTION public.submit_loa_request(
  p_user_id TEXT,
  p_user_tag TEXT,
  p_reason TEXT
) RETURNS BOOLEAN
LANGUAGE plpgsql
SET search_path = pg_catalog, public
AS $$
BEGIN
  INSERT INTO public.loa_requests (user_id, user_tag, reason, status)
  VALUES (p_user_id, p_user_tag, p_reason, 'Pending')
  ON CONFLICT (user_id) DO UPDATE
    SET user_tag = EXCLUDED.user_tag,
        reason = EXCLUDED.reason,
        status = 'Pending',
        created_at = NOW(),
        updated_at = NOW();

  INSERT INTO public.duty_status (user_id, status, updated_at)
  VALUES (p_user_id, 'LOA Pending', NOW())
  ON CONFLICT (user_id) DO UPDATE
    SET status = 'LOA Pending', updated_at = NOW();

  RETURN TRUE;
END;
$$;

CREATE OR REPLACE FUNCTION public.review_loa_request(
  p_user_id TEXT,
  p_approved BOOLEAN
) RETURNS BOOLEAN
LANGUAGE plpgsql
SET search_path = pg_catalog, public
AS $$
DECLARE
  affected_rows INTEGER;
BEGIN
  UPDATE public.loa_requests
  SET status = CASE WHEN p_approved THEN 'Approved' ELSE 'Rejected' END,
      updated_at = NOW()
  WHERE user_id = p_user_id AND status = 'Pending';

  GET DIAGNOSTICS affected_rows = ROW_COUNT;
  IF affected_rows = 0 THEN
    RETURN FALSE;
  END IF;

  INSERT INTO public.duty_status (user_id, status, updated_at)
  VALUES (p_user_id, CASE WHEN p_approved THEN 'On LOA' ELSE 'Off Duty' END, NOW())
  ON CONFLICT (user_id) DO UPDATE
    SET status = EXCLUDED.status, updated_at = NOW();

  RETURN TRUE;
END;
$$;

CREATE OR REPLACE FUNCTION public.clear_loa_request(p_user_id TEXT)
RETURNS BOOLEAN
LANGUAGE plpgsql
SET search_path = pg_catalog, public
AS $$
BEGIN
  DELETE FROM public.loa_requests WHERE user_id = p_user_id;

  INSERT INTO public.duty_status (user_id, status, updated_at)
  VALUES (p_user_id, 'Off Duty', NOW())
  ON CONFLICT (user_id) DO UPDATE
    SET status = 'Off Duty', updated_at = NOW();

  RETURN TRUE;
END;
$$;

REVOKE ALL ON FUNCTION public.submit_loa_request(TEXT, TEXT, TEXT) FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.review_loa_request(TEXT, BOOLEAN) FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.clear_loa_request(TEXT) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.submit_loa_request(TEXT, TEXT, TEXT) TO service_role;
GRANT EXECUTE ON FUNCTION public.review_loa_request(TEXT, BOOLEAN) TO service_role;
GRANT EXECUTE ON FUNCTION public.clear_loa_request(TEXT) TO service_role;
