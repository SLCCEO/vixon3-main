CREATE TABLE IF NOT EXISTS public.moderation_cases (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_system TEXT NOT NULL,
  source_id TEXT NOT NULL,
  case_number TEXT,
  platforms TEXT[] NOT NULL DEFAULT ARRAY[]::TEXT[],
  actions TEXT[] NOT NULL DEFAULT ARRAY[]::TEXT[],
  target_user_id TEXT,
  target_username TEXT,
  moderator_user_id TEXT,
  moderator_username TEXT,
  reason TEXT,
  appeal_status TEXT,
  status TEXT NOT NULL DEFAULT 'recorded',
  source_url TEXT,
  raw_content JSONB NOT NULL DEFAULT '[]'::JSONB,
  evidence JSONB NOT NULL DEFAULT '[]'::JSONB,
  occurred_at TIMESTAMPTZ,
  synced_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (source_system, source_id)
);

CREATE INDEX IF NOT EXISTS moderation_cases_platforms_actions_idx
  ON public.moderation_cases USING GIN (platforms, actions);

CREATE INDEX IF NOT EXISTS moderation_cases_target_user_id_idx
  ON public.moderation_cases (target_user_id);

CREATE INDEX IF NOT EXISTS moderation_cases_synced_at_idx
  ON public.moderation_cases (synced_at DESC);

ALTER TABLE public.moderation_cases ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.moderation_cases FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.moderation_cases TO service_role;

CREATE OR REPLACE FUNCTION public.search_moderation_cases(
  search_query TEXT,
  result_limit INTEGER DEFAULT 100,
  result_offset INTEGER DEFAULT 0
)
RETURNS TABLE (
  source_system TEXT,
  source_id TEXT,
  case_number TEXT,
  platforms TEXT[],
  actions TEXT[],
  target_user_id TEXT,
  target_username TEXT,
  moderator_username TEXT,
  reason TEXT,
  appeal_status TEXT,
  status TEXT,
  source_url TEXT,
  evidence JSONB,
  occurred_at TIMESTAMPTZ,
  synced_at TIMESTAMPTZ
)
LANGUAGE sql
STABLE
SECURITY INVOKER
SET search_path = ''
AS $$
  WITH search_term AS (
    SELECT replace(
      replace(
        replace(COALESCE(search_query, ''), E'\\', E'\\\\'),
        '%',
        E'\\%'
      ),
      '_',
      E'\\_'
    ) AS value
  )
  SELECT
    cases.source_system,
    cases.source_id,
    cases.case_number,
    cases.platforms,
    cases.actions,
    cases.target_user_id,
    cases.target_username,
    cases.moderator_username,
    cases.reason,
    cases.appeal_status,
    cases.status,
    cases.source_url,
    cases.evidence,
    cases.occurred_at,
    cases.synced_at
  FROM public.moderation_cases AS cases
  CROSS JOIN search_term
  WHERE search_term.value = ''
     OR concat_ws(
       ' ',
       cases.case_number,
       cases.source_system,
       cases.source_id,
       array_to_string(cases.platforms, ' '),
       array_to_string(cases.actions, ' '),
       cases.target_user_id,
       cases.target_username,
       cases.moderator_user_id,
       cases.moderator_username,
       cases.reason,
       cases.appeal_status,
       cases.status,
       cases.source_url,
       cases.raw_content::TEXT,
       cases.evidence::TEXT
     ) ILIKE '%' || search_term.value || '%' ESCAPE E'\\'
  ORDER BY cases.occurred_at DESC NULLS LAST, cases.synced_at DESC
  LIMIT LEAST(GREATEST(COALESCE(result_limit, 100), 1), 101)
  OFFSET GREATEST(COALESCE(result_offset, 0), 0);
$$;

REVOKE ALL ON FUNCTION public.search_moderation_cases(TEXT, INTEGER, INTEGER) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.search_moderation_cases(TEXT, INTEGER, INTEGER) TO service_role;

